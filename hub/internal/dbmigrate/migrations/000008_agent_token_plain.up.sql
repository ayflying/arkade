-- 待接入服务器的专属密钥明文。
--
-- 为什么需要它：用户在「添加服务器」后往往要过一阵才去目标机器上部署 Agent，
-- 期间会反复需要那把密钥和编排示例。只在创建响应里返回一次，用户关掉弹窗
-- 就只能重置密钥——重置会打断可能已经开始的接入，体验和语义都不对。
--
-- 边界：
--   * 只在记录仍处于 pending（从未接入）期间保存，第一次握手成功即清空；
--   * 接入成功后该列为空，列表页也不再提供查看入口；
--   * 认证仍以 token_hash 为准，本列只是给管理员回看的副本。
ALTER TABLE agent_tokens ADD COLUMN token_plain text NOT NULL DEFAULT '';
