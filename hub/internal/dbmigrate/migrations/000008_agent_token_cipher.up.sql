-- 待接入服务器的专属密钥密文。
--
-- 为什么需要它：用户在「添加服务器」后往往要过一阵才去目标机器上部署 Agent，
-- 期间会反复需要那把密钥和编排示例。只在创建响应里返回一次，用户关掉弹窗
-- 就只能重置密钥——重置会打断可能已经开始的接入，体验和语义都不对。
--
-- 安全边界（与 token_hash 并存的取舍）：
--   * 只在「记录仍是 pending（从未接入）」期间保存，第一次握手成功即清空；
--   * 不是明文：AES-GCM 加密，主密钥在独立的 settings_key_file 里，
--     只拖走数据库拿不到可用密钥；
--   * 接入成功后该列为空，此后与旧行为一致：Hub 无法反推明文。
ALTER TABLE agent_tokens ADD COLUMN token_cipher text NOT NULL DEFAULT '';
