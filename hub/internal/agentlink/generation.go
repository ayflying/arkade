// Package agentlink 的握手临界区设计说明（authMu）。
//
// 真正的实现在 credential_lock.go（EnrollmentGuard）。本文件只承载设计理由。
//
// ============================ 要解决的竞态 ============================
//
// 时序（全部真实可达，不是理论窗口）：
//
//	T1  Agent 用旧密钥建连 → authorize 查库通过（此刻摘要有效）
//	T2  管理员重置密钥 / 删除服务器 → 写库 + Registry.Close(agentID)
//	T3  T1 的连接此刻**还没进在线表**，Close 找不到它 —— 等于没关掉
//	T4  T1 继续走完握手 → OnAgentHello 落库 + Add → **旧密钥成功上线**
//
// 更糟的变体（删除场景）：T4 的 OnAgentHello 会把刚删掉的记录
// **重新建出来**，用户看到"删掉的服务器自己回来了"。
//
// ============================ 为什么不用 generation ============================
//
// 先前的方案是"按凭据版本号复核"：authorize 记下 generation，
// 注册前在锁内复核它是否仍然相等。它有两个治不好的毛病：
//
//  1. **快照本身不是原子的**：authorize 里 "查摘要 → 读 generation"
//     是两步，中间可能插入一次 reset（写库 + Bump）。
//     结果：查到了旧摘要（通过），却读到了**新** generation，
//     复核自然通过 —— 旧密钥照样放行。要修就得让"查库 + 读版本"
//     也进同一把锁，而那时已经等于"把整个验证放进临界区"了。
//  2. 它只覆盖"注册"这一步，覆盖不了 OnAgentHello 的**数据库写入**。
//     删除竞态体现在写库上，版本号管不到。
//
// ============================ 实际方案：一把独立的 authMu ============================
//
// 引入 EnrollmentGuard（内部一把独立的 authMu），把两类操作串行化：
//
//	A. 握手（专属路径）：
//	   authMu 内 → 重新校验 hash 仍绑定同一 agent_id → 确认未禁用
//	             → OnAgentHello 写库（仅更新已存在记录）→ Registry.Add
//	   全部在一个临界区里完成。
//
//	B. 撤销（reset / delete / disable）：
//	   authMu 内 → 写库 → Registry.Close
//	   同样一个临界区。
//
// 于是 A 与 B 必然完全串行：
//   - B 先拿到锁：A 进去时校验失败（摘要已换/记录已删/已禁用）→ 不上线、不写库；
//   - A 先拿到锁：A 已完成登记，B 的 Close 能在在线表里找到并断开它。
//
// 两种情况都不会留下"已撤销却仍在线"或"已删除却被复活"的记录。
//
// **为什么独立锁而不是复用 Registry.mu**：Registry.Close 与 Add 都要
// 拿 Registry.mu，若把 authMu 就用 Registry.mu，调用链会变成
// authMu→Close(mu)→…→Add(mu) 的嵌套，直接死锁。两把锁各自职责清晰：
// authMu 管"握手与撤销的互斥"，Registry.mu 只管在线表这一个数据结构。
//
// **代价**：专属路径的握手会全局串行（短事务）。管理操作是低频的，
// 握手也是低频的（每台机器一次），这个代价远小于"安全属性无法推理"。
// 但临界区内**绝不能有网络 I/O 或长时间操作**——见 EnrollmentGuard 的实现约束。
